export const calculateGrossSalary = (structure: {
  basicSalary: number;
  hra: number;
  conveyanceAllowance: number;
  medicalAllowance: number;
  specialAllowance: number;
  otherAllowances: number;
  bonus: number;
  overtimeAmount?: number;
}): number => {
  return (
    structure.basicSalary +
    structure.hra +
    structure.conveyanceAllowance +
    structure.medicalAllowance +
    structure.specialAllowance +
    structure.otherAllowances +
    structure.bonus +
    (structure.overtimeAmount || 0)
  );
};

export const calculateTotalDeductions = (structure: {
  providentFund: number;
  professionalTax: number;
  incomeTax: number;
  otherDeductions: number;
}): number => {
  return (
    structure.providentFund +
    structure.professionalTax +
    structure.incomeTax +
    structure.otherDeductions
  );
};

export const calculateNetSalary = (
  grossSalary: number,
  totalDeductions: number
): number => {
  return grossSalary - totalDeductions;
};
